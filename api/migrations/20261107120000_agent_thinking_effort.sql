UPDATE agent.gateway AS gw
SET stage_defaults = (
    SELECT COALESCE(jsonb_object_agg(stage.name, jsonb_build_object('maxTurns', stage.max_turns)), '{}')
    FROM (VALUES
        ('brainstorming', gw.max_turns_plan),
        ('design', gw.max_turns_plan),
        ('implementation_plan', gw.max_turns_plan),
        ('release_notes', gw.max_turns_plan),
        ('implementation', gw.max_turns_implement)
    ) AS stage (name, max_turns)
    WHERE stage.max_turns IS NOT NULL
);

