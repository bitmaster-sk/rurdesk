const asciiMap = {
    '<3': '💗',
    ':-D': '😁',
    ':)': '😄',
    ':-)': '😄',
    ':D': '😄',
    ';)': '😉',
    ';-)': '😉',
    ':(': '😒',
    ':-(': '😒',
    '%)': '😖',
    '%-)': '😖',
    ':-P': '😜',
    ':-b': '😜',
    ':-p': '😜',
    ':P': '😜',
    ':b': '😜',
    ':p': '😜',
    ':-O': '😲',
    ':-o': '😲',
    ':O': '😲',
    ':o': '😲',
    '>:(': '😠',
    '>:)': '😈',
    '>:-)': '😈',
    '>:/': '😡'
};

const asciiRegex =
    /(<3)|(:-D)|(:\))|(:-\))|(:D)|(;\))|(;-\))|(:\()|(:-\()|(%\))|(%-\))|(:-P)|(:-b)|(:-p)|(:P)|(:b)|(:p)|(:-O)|(:-o)|(:O)|(:o)|(>:\()|(>:\))|(>:-\))|(>:\/)/gm;

export function fromAsciiToEmoji(value: string): string {
    return value.replace(asciiRegex, r => (asciiMap[r] ? asciiMap[r] : r));
}
